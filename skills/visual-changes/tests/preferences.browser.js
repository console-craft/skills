async page => {
  await page.setViewportSize({ width: 1440, height: 950 });
  const url = "http://localhost:43720/template";
  const source = await (await page.request.get(url)).text();
  const data = JSON.parse(source.match(/<script id="tour-data" type="application\/json">([\s\S]*?)<\/script>/)[1]);
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  const mount = async (payload = data) => {
    const json = JSON.stringify(payload).replaceAll("<", "\\u003c");
    const html = source.replace(/(<script id="tour-data" type="application\/json">)[\s\S]*?(<\/script>)/, (_, a, b) => a + json + b);
    await page.route("https://preferences.test/tour", route => route.fulfill({ contentType: "text/html", body: html }));
    await page.goto("https://preferences.test/tour");
    await page.locator('body[data-viewer-state="ready"]').waitFor();
    await page.locator('#engine-status[data-state="loaded"]').waitFor();
  };
  await mount();
  await page.evaluate(() => localStorage.clear());
  await mount();
  const bodies = page.locator(".diff-body");
  const failures = [];
  if (await page.locator('#progress').getAttribute('aria-valuenow') !== '0') failures.push('Unread tour progress must start at zero');
  if (await page.locator('#excerpts button.diff-toolbar[data-action="collapse-diff"]').count() !== 1) failures.push('Whole diff header must be the native toggle button');
  if (await page.locator('[data-action="focus-excerpt"]').first().textContent() !== 'Focus on lines 1-5' || !(await page.locator('[data-action="focus-excerpt"]').first().getAttribute('aria-label')).includes('after-change')) failures.push('Focus label must be concise with revision context in its accessible name');
  if (await page.locator('#excerpts [data-field="file-status"]').count() !== 1) failures.push('File change status needs a separate badge');
  if (await page.locator('#excerpts [data-action="focus-excerpt"]').count() !== 1) failures.push('Focus range must be an actionable button');
  if ((await page.locator('.note-location').first().textContent()).includes(' · new')) failures.push('Note location must not show the ambiguous new suffix');
  if (!(await page.locator('#engine-status').textContent()).includes('loaded from CDN')) failures.push('Engine status must disclose CDN loading');
  if (await page.locator('.layout-controls > .eyebrow').evaluate(el => getComputedStyle(el).color) !== 'rgb(212, 190, 152)') failures.push('Important code heading must use default text color');
  if (await page.locator('[data-action="reset-context"]').count()) failures.push('Redundant context reset button must be removed');
  if ((await page.locator('#excerpts [aria-label="File context"] button').allTextContents()).join('|') !== 'Full file|Hunks') failures.push('Context uses the Full file / Hunks segmented group');
  check(failures.length === 0, failures.join('; '));
  const header = page.locator('#excerpts button.diff-toolbar').first();
  check(await header.locator('[data-field="source-path"]').count() === 1 && await header.locator('[data-field="file-stats"]').count() === 1, 'One toggle includes the complete path and counts');
  check(await header.locator('button').count() === 0, 'Header toggle has no nested collapse button');
  check(await header.locator('[data-field="file-status"]').evaluate(el => getComputedStyle(el).color) === 'rgb(212, 165, 153)', 'Modified file badge uses Gruvware accent');
  await header.focus(); await page.keyboard.press('Enter');
  await page.locator('#excerpts [data-code] [data-line="1"][data-selected-line]').first().waitFor();
  await page.keyboard.press('Space');
  check(await page.locator('#excerpts .diff-body').first().evaluate(el => el.hidden), 'Enter/Space toggle the whole header accessibly');
  const focus = page.locator('#excerpts [data-action="focus-excerpt"]').first();
  await focus.click();
  await page.locator('#excerpts [data-code] [data-line="1"][data-selected-line]').first().waitFor();
  check(await page.locator('#excerpts .diff-body').first().evaluate(el => !el.hidden), 'Focus action opens its collapsed diff');
  await page.locator('#notes button').first().click();
  await focus.click();
  await page.locator('#excerpts [data-code] [data-line="5"][data-selected-line]').first().waitFor();
  check(await page.locator('#notes button[aria-pressed="true"]').count() === 0, 'Focus action clears active note state and restores the whole range');
  await page.locator('#excerpts [data-column-number="2"]').first().click();
  await page.waitForFunction(() => !document.querySelector('#excerpts diffs-container')?.shadowRoot?.querySelector('[data-code] [data-line="5"][data-selected-line]'));
  await focus.click();
  await page.locator('#excerpts [data-code] [data-line="1"][data-selected-line]').first().waitFor();
  await page.locator('#excerpts [data-code] [data-line="5"][data-selected-line]').first().waitFor();
  await header.click();
  const bulk = page.locator("#collapse-all-diffs");
  check(await bodies.evaluateAll(els => els.every(el => el.hidden)), "Fresh tour starts with every diff collapsed");
  check(await bulk.textContent() === "Reveal all diffs", "Fresh bulk label reflects collapsed default");
  await page.locator("#next").click();
  check(await page.locator('#progress').getAttribute('aria-valuenow') === '0', 'Navigation alone never increases read progress');
  check(await page.locator('#related-list details').count() === 0, "Supporting files have no extra disclosure wrapper");
  check(await page.locator('#related-list [data-component="source-diff"]').count() > 0, "Supporting files use the same single diff card");
  check(await bodies.evaluateAll(els => els.every(el => el.hidden)), "Supporting and primary cards both start collapsed");
  await bulk.click();
  await page.locator('#related-list [data-code]').first().waitFor();
  await page.locator('#excerpts [data-code] [data-line="1"][data-selected-line]').first().waitFor();
  check(await page.locator('#related-list [data-field="file-status"]').textContent() === 'Added', 'Added file is labeled independently from after-change coordinates');
  check(await page.locator('#related-list [data-field="file-status"]').evaluate(el => getComputedStyle(el).color) === 'rgb(186, 197, 132)', 'Added file badge uses the additions green');
  check(await bodies.evaluateAll(els => els.every(el => !el.hidden)), "Bulk expands primary and supporting cards together");
  await page.locator("#split").click();
  await page.locator("#mark-read").click();
  check(await page.locator('#rail button[aria-current="step"] .bullet.read').evaluate(el => getComputedStyle(el).color) === 'rgb(186, 197, 132)', 'Active read checkmark remains green');
  await mount();
  check(await page.locator('#rail .bullet.read').evaluate(el => getComputedStyle(el).color) === 'rgb(186, 197, 132)', 'Inactive read checkmark remains green');
  check(await page.locator("#split").getAttribute("aria-pressed") === "true", "Layout persists after reload");
  check(await bodies.evaluateAll(els => els.every(el => !el.hidden)), "Bulk expand preference persists across stops and reload");
  check(await page.locator("#rail-count").textContent() === "1 / 4 read", "Read stop identity survives reload");
  check(await page.locator('#progress').getAttribute('aria-valuenow') === '1', 'Saved read progress restores independently of active position');
  await page.locator('#excerpts [data-context="full"]').first().click();
  await page.locator('#excerpts [data-action="collapse-diff"]').first().click();
  await mount();
  check(await page.locator('#excerpts .diff-body').first().evaluate(el => el.hidden), "Individual card collapse persists");
  check(await page.locator('#excerpts [data-context="full"]').first().getAttribute('aria-pressed') === 'true', "Full-context preference persists per card");
  await page.locator("#next").click();
  check(await page.locator("#mark-read").getAttribute("aria-pressed") === "true", "Saved read mark belongs to the same stop");
  await page.locator("#mark-read").click();
  await bulk.click();
  await mount();
  check(await bodies.evaluateAll(els => els.every(el => el.hidden)), "Bulk collapse survives reload");
  check(await page.locator("#rail-count").textContent() === "0 / 4 read", "Mark-unread also persists");
  const other = JSON.parse(JSON.stringify(data)); other.comparison.head = "another-head";
  await mount(other);
  check(await page.locator("#unified").getAttribute("aria-pressed") === "true", "Another comparison does not inherit layout");
  check(await bodies.evaluateAll(els => els.every(el => el.hidden)), "Another comparison starts collapsed");
  await page.evaluate(() => { for (const key of Object.keys(localStorage)) localStorage.setItem(key, "{broken-json"); });
  await mount();
  check(await bodies.evaluateAll(els => els.every(el => el.hidden)), "Corrupt saved JSON falls back safely");
  const progressTour = JSON.parse(JSON.stringify(data)); progressTour.comparison.head = 'progress-only-head';
  await mount(progressTour);
  for (const stop of await page.locator('#rail button').all()) { await stop.click(); await page.locator('#mark-read').click(); }
  check(await page.locator('#progress-fill').evaluate(el => el.style.width) === '100%', 'Only marking every stop read reaches full progress');
  await page.locator('#mark-read').click();
  check(await page.locator('#progress-fill').evaluate(el => el.style.width) === '75%', 'Marking one stop unread reduces progress while staying at the final stop');
  const partial = JSON.parse(JSON.stringify(data));
  partial.comparison.head = "patch-only-head";
  partial.files = [{ path: "src/config.ts", status: "modified", additions: 1, deletions: 1, unavailableReason: "Full source unavailable.", patch: "diff --git a/src/config.ts b/src/config.ts\n--- a/src/config.ts\n+++ b/src/config.ts\n@@ -42 +42 @@\n-export const timeout = 1000;\n+export const timeout = 2000;\n" }];
  partial.stops = [{ id: "patch", title: "Patch", shortTitle: "Patch", summary: "A supplied patch.", excerpts: [{ id: "code", path: "src/config.ts", side: "new", start: 42, end: 42 }], relatedFiles: [], notes: [{ excerptId: "code", side: "new", line: 42, title: "Original coordinate", body: "This note must reveal the available patch." }] }];
  await mount(partial);
  await page.locator("#notes button").click();
  await page.locator('[data-code] [data-line="42"][data-selected-line]').first().waitFor();
  check(await page.locator('[data-context="full"]').isDisabled(), "Patch note reveals real code without promising unavailable full context");
  await page.locator('[data-action="collapse-diff"]').click();
  await page.locator('[data-action="focus-excerpt"]').click();
  await page.locator('[data-code] [data-line="42"][data-selected-line]').first().waitFor();
  check(await page.locator('#notes button[aria-pressed="true"]').count() === 0, 'Patch-only refocus clears note ownership without inventing context');
  for (const renamed of [false, true]) {
    const hidden = JSON.parse(JSON.stringify(partial)); hidden.comparison.head = `hidden-focus-${renamed}`;
    const before = Array.from({ length: 90 }, (_, i) => `export const item${i + 1} = ${i + 1};`).join('\n') + '\n';
    hidden.files = [{ path: 'src/config.ts', status: renamed ? 'renamed' : 'modified', ...(renamed ? { previousPath: 'before.ts' } : {}), additions: renamed ? 0 : 1, deletions: renamed ? 0 : 1, source: { old: before, next: renamed ? before : before.replace('item40 = 40', 'item40 = 400') } }];
    hidden.stops[0].notes = []; hidden.stops[0].excerpts = [{ id: 'gap', path: 'src/config.ts', side: 'old', start: 1, end: 3 }];
    await mount(hidden);
    await page.locator('[data-action="focus-excerpt"]').click();
    await page.locator('[data-code] [data-line="3"][data-selected-line]').first().waitFor();
    check(await page.locator('[data-context="full"]').getAttribute('aria-pressed') === 'true', 'Hidden-context and pure-rename focus actions reveal actual complete source');
  }
  await page.evaluate(() => localStorage.clear());
  await page.addInitScript(() => { Storage.prototype.getItem = Storage.prototype.setItem = () => { throw new Error("Storage blocked"); }; });
  await mount();
  await page.locator("#storage-status").waitFor({ state: "visible" });
  await bulk.click();
  await page.locator('[data-code]').first().waitFor();
  await page.locator("#mark-read").click();
  check(await page.locator("#rail-count").textContent() === "1 / 4 read", "Blocked storage leaves in-memory controls working");
  return "PASS: collapsed defaults, single supporting cards, persistent layout/bulk/read/unread, comparison isolation, corrupt/blocked storage";
}
