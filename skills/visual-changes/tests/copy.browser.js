async page => {
  const source = await (await page.request.get('http://localhost:43720/template')).text();
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'], { origin: 'https://copy.test' });
  const data = {
    comparison: { repository: 'test/copy', title: 'Copy source', kind: 'commit', mergeBase: 'old', head: 'new' },
    files: [{ path: 'sample.txt', status: 'modified', additions: 3, deletions: 3, source: { old: 'old first\nold second\r\nold <&> final', next: 'new first\nnew second\r\nnew <&> final' } }],
    stops: [{ id: 'copy', title: 'Copy', shortTitle: 'Copy', summary: 'Copy real source, not the DOM.', excerpts: [{ id: 'after', path: 'sample.txt', side: 'new', start: 1, end: 2 }, { id: 'before', path: 'sample.txt', side: 'old', start: 1, end: 3 }], relatedFiles: [], notes: [{ excerptId: 'before', side: 'old', line: 2, title: 'Old line', body: 'Preserve this exact source.' }] }]
  };
  const mount = async (payload, waitForRenderer = true) => {
    const json = JSON.stringify(payload).replaceAll('<', '\\u003c');
    const html = source.replace(/(<script id="tour-data" type="application\/json">)[\s\S]*?(<\/script>)/, (_, a, b) => a + json + b);
    await page.route('https://copy.test/tour', route => route.fulfill({ contentType: 'text/html', body: html }));
    await page.goto('https://copy.test/tour');
    if (waitForRenderer) await page.locator('#engine-status[data-state="loaded"]').waitFor();
    if (await page.locator('#collapse-all-diffs').textContent() === 'Reveal all diffs') await page.locator('#collapse-all-diffs').click();
    if (waitForRenderer) await page.locator('[data-code]').first().waitFor();
  };
  await mount(data);
  const after = page.locator('#excerpts [data-component="source-diff"]').first();
  const before = page.locator('#excerpts [data-component="source-diff"]').nth(1);
  const copyAfter = after.locator('[data-action="copy-selection"]');
  check(await copyAfter.count() === 1, 'Selection area must become a real copy button');
  check(await copyAfter.textContent() === 'Copy selected new lines 1–2', 'Focus selection exposes exact revision and range');
  check(await copyAfter.getByText('new lines', { exact: true }).count() === 1, 'Copy button colors the complete new lines phrase');
  check(await copyAfter.getByText('new lines', { exact: true }).evaluate(el => getComputedStyle(el).color) === 'rgb(186, 197, 132)', 'New lines phrase uses Gruvware additions green');
  check(await copyAfter.evaluate(el => !el.classList.contains('ghost')), 'Selected copy action is a regular button');
  await copyAfter.click();
  check(await page.evaluate(() => navigator.clipboard.readText()) === 'new first\nnew second\r\n', 'Native clipboard gets exact new-side source with whitespace, not diff markers');
  check(await after.locator('[data-field="copy-status"]').textContent() === 'Copied.', 'Copy success is the concise Copied. message');
  await page.locator('#notes button').click();
  const copyBefore = before.locator('[data-action="copy-selection"]');
  check(await copyBefore.textContent() === 'Copy selected old lines 2–2', 'Note selection updates copy action to old side');
  check(await copyBefore.getByText('old lines', { exact: true }).evaluate(el => getComputedStyle(el).color) === 'rgb(222, 152, 128)', 'Old lines phrase uses Gruvware deletions color');
  await copyBefore.click();
  check(await page.evaluate(() => navigator.clipboard.readText()) === 'old second\r\n', 'Old-side note copies original CRLF source');
  await page.locator('#excerpts [data-action="focus-excerpt"]').nth(1).click();
  await copyBefore.click();
  check(await page.evaluate(() => navigator.clipboard.readText()) === data.files[0].source.old, 'Whole range preserves missing final newline and literal special characters');
  await page.locator('#notes button').click();
  check(await before.locator('[data-field="copy-status"]').textContent() === '', 'Changing a selection to a note clears previous copy feedback');
  await before.locator('[data-gutter] [data-line-type="change-deletion"][data-column-number="1"]').click();
  await page.locator('#split').click();
  check(await copyBefore.textContent() === 'Copy selected old lines 1–1', 'Manual selection after a note survives layout changes instead of restoring the note');
  await page.locator('#excerpts [data-action="focus-excerpt"]').first().click();
  await page.locator('#unified').click();
  const gutter = (card, type, line) => card.locator(`[data-gutter] [data-line-type="change-${type}"][data-column-number="${line}"]`);
  const drag = async (from, to) => {
    await from.scrollIntoViewIfNeeded(); await to.scrollIntoViewIfNeeded();
    const a = await from.boundingBox(), b = await to.boundingBox();
    await page.mouse.move(a.x + a.width / 2, a.y + a.height / 2);
    await page.mouse.down(); await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2, { steps: 8 }); await page.mouse.up();
  };
  await drag(gutter(after, 'addition', 3), gutter(after, 'addition', 1));
  check(await copyAfter.textContent() === 'Copy selected new lines 1–3', 'Reverse manual selection normalizes the original range');
  await copyAfter.click();
  check(await page.evaluate(() => navigator.clipboard.readText()) === 'new first\nnew second\r\nnew <&> final', 'Reverse manual selection copies only new-side source');
  await drag(gutter(after, 'deletion', 1), gutter(after, 'addition', 2));
  check(await copyAfter.isHidden(), 'Mixed-side selections cannot expose a misleading copy action');
  check((await after.locator('[data-field="selection-hint"]').textContent()).includes('just one side'), 'Mixed-side selection explains how to copy');
  await gutter(after, 'deletion', 2).click();
  check(await copyAfter.textContent() === 'Copy selected old lines 2–2', 'Manual old-side selection overrides the new-side focus');
  await copyAfter.click();
  check(await page.evaluate(() => navigator.clipboard.readText()) === 'old second\r\n', 'Manual old-side selection copies old text');
  await gutter(after, 'deletion', 2).click();
  check(await copyAfter.isHidden(), 'Clearing a manual selection hides the copy button');
  check(await after.locator('[data-field="selection-hint"]').isVisible(), 'Clearing a selection restores the hint');
  await page.locator('#split').click();
  await drag(gutter(after, 'addition', 1), gutter(after, 'addition', 2));
  await copyAfter.click();
  check(await page.evaluate(() => navigator.clipboard.readText()) === 'new first\nnew second\r\n', 'Split-layout selection copies the indicated revision');
  await page.evaluate(() => { const write = navigator.clipboard.writeText.bind(navigator.clipboard); window.restoreCopy = () => { navigator.clipboard.writeText = write; }; navigator.clipboard.writeText = text => new Promise(resolve => { window.finishCopy = async () => { await write(text); resolve(); }; }); });
  await copyAfter.click();
  await gutter(after, 'addition', 3).click();
  await page.evaluate(() => window.finishCopy());
  await copyAfter.waitFor({ state: 'visible' });
  check(await after.locator('[data-field="copy-status"]').textContent() === '', 'A delayed copy cannot label a newer selection as copied');
  await page.evaluate(() => window.restoreCopy());
  await page.locator('#excerpts [data-action="focus-excerpt"]').nth(1).click();
  await copyBefore.click();
  await page.evaluate(() => { navigator.clipboard.writeText = async () => { throw new Error('Permission denied'); }; });
  await copyAfter.click();
  await after.locator('[data-field="copy-status"]').filter({ hasText: 'Could not copy' }).waitFor();
  check(await page.evaluate(() => navigator.clipboard.readText()) === data.files[0].source.old, 'Clipboard denial never reports success or overwrites previous content');
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { value: undefined, configurable: true }));
  await copyAfter.click();
  check((await after.locator('[data-field="copy-status"]').textContent()).includes('Could not copy'), 'Missing clipboard API explains failure without crashing');
  const partial = JSON.parse(JSON.stringify(data));
  partial.comparison.head = 'patch'; partial.files = [{ path: 'sample.txt', status: 'modified', additions: 1, deletions: 1, patch: 'diff --git a/sample.txt b/sample.txt\n--- a/sample.txt\n+++ b/sample.txt\n@@ -42 +42 @@\n-old text\n+new text\n\\ No newline at end of file\n', unavailableReason: 'Full source unavailable.' }];
  partial.stops[0].excerpts = [{ id: 'patch', path: 'sample.txt', side: 'new', start: 42, end: 42 }]; partial.stops[0].notes = [];
  await mount(partial);
  await copyAfter.click();
  check(await page.evaluate(() => navigator.clipboard.readText()) === 'new text', 'Patch-only copy uses original line 42 and respects no-final-newline metadata');
  await gutter(after, 'deletion', 42).click();
  check(await copyAfter.isHidden(), 'Pierre toggles an already selected numeric range off even across revision sides');
  await gutter(after, 'deletion', 42).click();
  await copyAfter.click();
  check(await page.evaluate(() => navigator.clipboard.readText()) === 'old text\n', 'Patch old-side source retains its final newline');
  partial.files[0].patch += '@@ -50 +50 @@\n-old tail\n+new tail\n';
  partial.comparison.head = 'patch-gap';
  await mount(partial);
  await page.locator('#unified').click();
  await drag(gutter(after, 'addition', 42), gutter(after, 'addition', 50));
  check(await copyAfter.isHidden(), 'A range spanning unavailable patch context cannot be copied');
  check((await after.locator('[data-field="selection-hint"]').textContent()).includes('not all present'), 'Missing patch lines receive an honest source-availability explanation');
  const engineUrl = 'https://esm.sh/@pierre/diffs@1.6.4?bundle';
  let release;
  const gate = new Promise(resolve => { release = resolve; });
  await page.route(engineUrl, async route => { await gate; await route.continue(); });
  data.comparison.head = 'loading-cdn';
  await mount(data, false);
  await page.locator('#notes button').click();
  check(await copyBefore.textContent() === 'Copy selected old lines 2–2', 'Note selection updates copying even before the CDN renderer is ready');
  await copyBefore.click();
  check(await page.evaluate(() => navigator.clipboard.readText()) === 'old second\r\n', 'Copying a note during CDN loading uses its source, not the previous focus');
  release();
  await page.locator('#engine-status[data-state="loaded"]').waitFor();
  await page.unroute(engineUrl);
  check(await copyBefore.textContent() === 'Copy selected old lines 2–2', 'Renderer initialization preserves the note copy range');
  return 'PASS: native old/new clipboard, focus/notes/manual/reverse/cleared/mixed selections, unified/split, exact CRLF/no-final-newline/special characters, denied/missing clipboard, pending-write feedback, original-coordinate patch copy and missing context, notes before CDN readiness';
}
